defmodule HcpConformance.CLI do
  @moduledoc """
  Command-line runner, used by `mix hcp.conformance`, the escript and the Docker
  image (`bin/hcp_conformance eval`).

      hcp_conformance --target https://vault.example.com \\
        --hook-url https://vault.example.com/conformance-hook --hook-secret "$HCP_HOOK_SECRET"

  Credentials may come from the environment instead of flags, so they stay out
  of shell history: HCP_HOOK_SECRET, HCP_PERSON_TOKEN, HCP_AGENT_TOKEN.

  Exit status: 0 when no MUST check failed, 1 when one did, 2 for a usage error.
  With `--strict`, an incomplete run (MUST checks skipped) also exits 1.
  """

  alias HcpConformance.{Catalog, Report}

  @switches [
    target: :string,
    discovery_url: :string,
    hook_url: :string,
    hook_secret: :string,
    person_token: :string,
    agent_token: :string,
    subject_did: :string,
    category: :string,
    groups: :string,
    only: :string,
    allow_private: :boolean,
    json: :string,
    verbose: :boolean,
    strict: :boolean,
    list: :boolean,
    help: :boolean,
    check_timeout_ms: :integer
  ]

  @doc "Escript entry point."
  @spec main([String.t()]) :: no_return()
  def main(argv) do
    {:ok, _apps} = Application.ensure_all_started(:req)
    System.halt(run(argv))
  end

  @doc "Runs the CLI and returns the exit status."
  @spec run([String.t()]) :: non_neg_integer()
  def run(argv) do
    case OptionParser.parse(argv, strict: @switches) do
      {opts, [], []} ->
        execute(opts)

      {_opts, args, invalid} ->
        usage_error("unexpected arguments: #{inspect(args ++ Enum.map(invalid, &elem(&1, 0)))}")
    end
  end

  defp execute(opts) do
    cond do
      opts[:help] -> print(@moduledoc)
      opts[:list] -> print(catalogue())
      true -> run_suite(opts)
    end
  end

  defp run_suite(opts) do
    attrs =
      opts
      |> Keyword.take([
        :target,
        :discovery_url,
        :hook_url,
        :subject_did,
        :category,
        :groups,
        :only,
        :allow_private,
        :check_timeout_ms
      ])
      |> Keyword.put(:hook_secret, opts[:hook_secret] || System.get_env("HCP_HOOK_SECRET"))
      |> Keyword.put(:person_token, opts[:person_token] || System.get_env("HCP_PERSON_TOKEN"))
      |> Keyword.put(:agent_token, opts[:agent_token] || System.get_env("HCP_AGENT_TOKEN"))

    progress = fn
      {:result, result} -> IO.write(:stderr, progress_mark(result.status))
      {:finished, _report} -> IO.write(:stderr, "\n")
      _other -> :ok
    end

    case HcpConformance.run(attrs, on_event: progress) do
      {:ok, report} ->
        IO.write(Report.to_text(report, verbose: opts[:verbose]))

        if opts[:json],
          do: File.write!(opts[:json], Jason.encode_to_iodata!(report, pretty: true))

        exit_status(report, opts[:strict])

      {:error, message} ->
        usage_error(message)
    end
  end

  defp exit_status(%{verdict: "fail"}, _strict), do: 1
  defp exit_status(%{verdict: "incomplete"}, true), do: 1
  defp exit_status(_report, _strict), do: 0

  defp progress_mark(:pass), do: "."
  defp progress_mark(:fail), do: "F"
  defp progress_mark(:warn), do: "W"
  defp progress_mark(:skip), do: "s"
  defp progress_mark(:error), do: "E"
  defp progress_mark(:na), do: "-"

  defp usage_error(message) do
    IO.puts(:stderr, "error: " <> message <> "\nRun with --help for usage.")
    2
  end

  @doc "The check catalogue as Markdown (docs/CHECKS.md)."
  @spec catalogue() :: String.t()
  def catalogue do
    rows =
      Catalog.all()
      |> Enum.group_by(& &1.group)
      |> then(fn grouped -> Enum.map(Catalog.groups(), &{&1, grouped[&1] || []}) end)
      |> Enum.map(fn {group, checks} ->
        Enum.join(
          [
            "## #{group}",
            "",
            "| Check | Section | Level | Requirement | Needs |",
            "| --- | --- | --- | --- | --- |" | Enum.map(checks, &catalogue_row/1)
          ],
          "\n"
        )
      end)

    total = length(Catalog.all())

    """
    # Check catalogue

    Generated by `mix hcp.checks`. #{total} checks against HCP v1 #{Report.spec_version()}.

    "Needs" lists what a run must have for the check to run; see `HcpConformance.Check`.

    #{Enum.join(rows, "\n\n")}
    """
  end

  @spec catalogue_row(HcpConformance.Check.t()) :: String.t()
  defp catalogue_row(check) do
    needs =
      if check.requires == [],
        do: "—",
        else: Enum.map_join(check.requires, ", ", &"`#{&1}`")

    "| `#{check.id}` | §#{check.section} | #{String.upcase(to_string(check.level))} | #{check.title} | #{needs} |"
  end

  @spec print(String.t()) :: 0
  defp print(text) do
    IO.puts(text)
    0
  end
end
